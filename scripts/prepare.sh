#!/bin/bash
# Prepares the tree for xcodebuild (CI and local): Libbox.xcframework (pinned release + sha256 from the public
# DE0CH/libbox-apple), the sing-box rule sets, App/Generated/Secrets.swift and a build-time snapshot of both
# subscriptions (from env LIANGXIN_SUB_URL / GULU_SUB_URL; when a live fetch fails here, the stored snapshot in
# LIANGXIN_SUB_SNAPSHOT / GULU_SUB_SNAPSHOT — 咕噜云's host refuses GitHub's runners), the China node (env
# CN_NODE_JSON: our Guangzhou server's outbounds as a sing-box profile; without it the build warns and China races
# direct alone), then `xcodegen generate`.
# Never prints the subscription URLs or contents.
set -euo pipefail
cd "$(dirname "$0")/.."
LIBBOX_TAG=v1.14.3-r1
LIBBOX_SHA=ac9a6e32c9eaad65fd561964aa41aa8dfd568b764b76d84dd92ce5c18a2566e5
UA="SFI/1.12.0 (sing-box 1.12.0)"

if [ ! -d Libbox.xcframework ] || [ "$(cat Libbox.xcframework/.tag 2>/dev/null)" != "$LIBBOX_TAG" ]; then
  rm -rf Libbox.xcframework
  curl -fsSL -o /tmp/Libbox.zip "https://github.com/DE0CH/libbox-apple/releases/download/$LIBBOX_TAG/Libbox.xcframework.zip"
  echo "$LIBBOX_SHA  /tmp/Libbox.zip" | shasum -a 256 -c -
  unzip -q /tmp/Libbox.zip && rm /tmp/Libbox.zip && echo "$LIBBOX_TAG" > Libbox.xcframework/.tag
fi

mkdir -p PacketTunnel/Rules
for f in geosite-cn geosite-category-ai-!cn; do
  curl -fsSL -o "PacketTunnel/Rules/$f.srs" "https://raw.githubusercontent.com/SagerNet/sing-geosite/rule-set/$f.srs"
done
curl -fsSL -o PacketTunnel/Rules/geoip-cn.srs https://raw.githubusercontent.com/SagerNet/sing-geoip/rule-set/geoip-cn.srs
ls -l PacketTunnel/Rules/*.srs

mkdir -p App/Generated App/Bundled/Subscriptions
esc() { printf %s "$1" | sed 's/\\/\\\\/g;s/"/\\"/g'; }
cat > App/Generated/Secrets.swift <<SWIFT
// Generated by scripts/prepare.sh from the repository secrets. Not committed.
enum Secrets {
    static let liangxinSubscription = "$(esc "${LIANGXIN_SUB_URL:-}")"
    static let guluSubscription = "$(esc "${GULU_SUB_URL:-}")"
}
SWIFT
for a in liangxin gulu; do
  v=$(echo "$a" | tr a-z A-Z)_SUB_URL; u="${!v:-}"
  rm -f "App/Bundled/Subscriptions/$a.json"
  [ -n "$u" ] || { echo "$a: no URL, no bundled snapshot"; continue; }
  if curl -fsS -m 30 -A "$UA" -o "/tmp/$a.json" "$u" && python3 -c "import json,sys; d=json.load(open(sys.argv[1])); assert len(d['outbounds'])>3" "/tmp/$a.json"; then
    mv "/tmp/$a.json" "App/Bundled/Subscriptions/$a.json"; echo "$a: bundled snapshot ok"
  else
    rm -f "/tmp/$a.json"
    sv=$(echo "$a" | tr a-z A-Z)_SUB_SNAPSHOT
    if [ -n "${!sv:-}" ]; then
      printf '%s' "${!sv}" > "App/Bundled/Subscriptions/$a.json"; echo "::warning::$a live fetch failed here; bundled the stored snapshot ($sv)"
    else
      echo "::warning::$a subscription fetch failed; no bundled snapshot"
    fi
  fi
done
rm -f App/Bundled/Subscriptions/cn.json
if [ -n "${CN_NODE_JSON:-}" ] && printf '%s' "$CN_NODE_JSON" | python3 -c "import json,sys; assert json.load(sys.stdin)['outbounds']" 2>/dev/null; then
  printf '%s' "$CN_NODE_JSON" > App/Bundled/Subscriptions/cn.json; echo "cn: bundled China node ok"
else
  echo "::warning::no valid CN_NODE_JSON: this build has no China node (China races direct alone)"
fi
touch App/Bundled/Subscriptions/.keep

command -v xcodegen >/dev/null || brew install xcodegen >/dev/null
xcodegen generate --quiet
